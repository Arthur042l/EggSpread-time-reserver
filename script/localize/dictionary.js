let currentLang = 'en';

export function getSystemLanguage() {
    const navLang = (navigator.language || navigator.userLanguage || 'en').toLowerCase();
    if (navLang.startsWith('zh-cn') || navLang.startsWith('zh-hans')) return 'zh-CN';
    if (navLang.startsWith('zh')) return 'zh';
    return 'en';
}

export function getCurrentLang() {
    return currentLang;
}

export function getText(key) {
    const dict = translations[currentLang] || translations.en;
    return dict[key] || translations.en[key] || key;
}

export function applyLanguage(langSetting) {
    let targetLang = langSetting;
    if (!targetLang || targetLang === 'auto') {
        targetLang = getSystemLanguage();
    }

    currentLang = translations[targetLang] ? targetLang : 'en';

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        const text = getText(key);
        if (text) el.innerText = text;
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        const text = getText(key);
        if (text) el.setAttribute('placeholder', text);
    });

    document.documentElement.lang = currentLang;
}

export function setAppLanguage(langSetting) {
    localStorage.setItem('dateMatch_lang', langSetting);
    applyLanguage(langSetting);
}

export function initLanguage() {
    const savedSetting = localStorage.getItem('dateMatch_lang') || 'auto';
    const selectEl = document.getElementById('app-language-select');
    if (selectEl) {
        selectEl.value = savedSetting;
    }
    applyLanguage(savedSetting);
}